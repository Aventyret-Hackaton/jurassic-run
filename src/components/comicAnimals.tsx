/**
 * Tecknade djur i serietidningsstil: platta färger, tjock svart tuschkontur,
 * skuggor med streckning och vita/blå kantljus. Alla djur tittar åt höger.
 * Koordinater: viewBox 0 0 200 150, marken ligger vid y ≈ 138.
 */
import type { ReactElement } from "react";

export const INK = "#141019";
const CREAM = "#f3e6c4";
const WHITE = "#ffffff";
const RIM = "#9fd8ff"; // kantljus på mörka djur

interface Fx { hatch: string; hex: string }
export interface ComicAnimal { bg: string; draw: (fx: Fx) => ReactElement }

const stroke = { stroke: INK, strokeWidth: 3, strokeLinejoin: "round" as const, strokeLinecap: "round" as const };

/** Fylld form med tuschkontur. */
const P = ({ d, f }: { d: string; f: string }) => <path d={d} fill={f} {...stroke} />;
/** Streckad skugga. */
const H = ({ d, fx }: { d: string; fx: Fx }) => <path d={d} fill={fx.hatch} stroke="none" />;
/** Linje utan fyllning. */
const L = ({ d, c = INK, w = 2 }: { d: string; c?: string; w?: number }) => (
  <path d={d} fill="none" stroke={c} strokeWidth={w} strokeLinecap="round" strokeLinejoin="round" />
);
/** Tunt ben/fågelben: tuschkontur under färgen. */
const Stalk = ({ d, c }: { d: string; c: string }) => (
  <>
    <path d={d} fill="none" stroke={INK} strokeWidth={11} strokeLinecap="round" />
    <path d={d} fill="none" stroke={c} strokeWidth={6} strokeLinecap="round" />
  </>
);
/** Seriegubbsöga med bister ögonbryn. */
const Eye = ({ x, y, r = 4, brow = true }: { x: number; y: number; r?: number; brow?: boolean }) => (
  <>
    <circle cx={x} cy={y} r={r} fill={WHITE} stroke={INK} strokeWidth={2} />
    <circle cx={x + r * 0.35} cy={y} r={r * 0.45} fill={INK} />
    {brow && <L d={`M${x - r * 2} ${y - r * 1.9} L${x + r * 1.6} ${y - r * 0.9}`} w={3} />}
  </>
);

